def compute_cramer_v_contingency_matrix(df, categorical_features):
    """
    Compute the Cramér's V matrix for a dataframe and a list of categorical features.


    Don't apply yates correction if one cell of the table has an **expected** count smaller than 5, according to 
    # https://en.wikipedia.org/wiki/Yates%27s_correction_for_continuity.
    # Yates correction prevents overestimation of statistical significance for small data.

    Parameters
    ----------
    df : pd.DataFrame
        The dataframe to analyze.
    categorical_features : list
        The list of categorical features to analyze.

    Returns
    -------
    pd.DataFrame
        The Cramér's V matrix.
    """
    cramer_v = pd.DataFrame(index=categorical_features, columns=categorical_features)

    for feature_1 in categorical_features:
        for feature_2 in categorical_features:
            obs2x2 = pd.crosstab(df[feature_1], df[feature_2])
            expected = np.outer(obs2x2.sum(axis=1), obs2x2.sum(axis=0)) / obs2x2.sum().sum()
            # Yates correction
            correction = np.any(expected < 5)
            cramer_v.loc[feature_1, feature_2] = association(obs2x2, method='cramer', correction=correction)
    return cramer_v.astype(np.float64)


def plot_cramer_v_heatmap(cramer_v_contingency_matrix, label="", ax=None):
    """
    Plot the Cramér's V matrix heatmap.
    
    Parameters:
    -----------
    cramer_v_contingency_matrix: pd.DataFrame
        The Cramér's V matrix of contingency coefficients.
    label: str
        The label to add to the title of the plot.
    ax: matplotlib.axes.Axes
        The axes to plot the heatmap on.

    Returns:
    --------
    None
    """
    sns.heatmap(cramer_v_contingency_matrix.round(2), cmap='coolwarm', annot=True, vmin=0, vmax=1, ax=ax)
    ax.set_title(f"Cramér's V contingency coefficient heatmap {label}")


def get_overall_stats(df, nan_value, round_decimals=2):
    stats = {}
    stats['n_rows'] = len(df)
    stats['n_cols'] = len(df.columns)
    stats['n_na_rows'] = len(df)-len(df.replace(nan_value, np.nan).dropna())
    stats['na_rows_%'] = stats['n_na_rows']/stats['n_rows']*100
    stats['n_duplicates'] = df.duplicated().sum()
    stats['duplicates_%'] = stats['n_duplicates']/stats['n_rows']*100
    stats = pd.DataFrame(stats, index=['dataset'])

    return stats if round_decimals is None else stats.round(round_decimals)