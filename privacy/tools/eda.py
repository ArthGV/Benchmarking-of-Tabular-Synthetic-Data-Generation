def get_categorical_features_stats(df, is_replace_na=False, round_decimals=2):
    """
    Get the statistics of the categorical features of a dataframe.

    Parameters
    ----------
    df : pd.DataFrame
        The dataframe to analyze.
    replace_na : bool, optional
        The value to replace as NA, by default -9.

    Returns
    -------
    pd.DataFrame
        The statistics of the categorical features.
    """
    stats_cat = df.describe(include=['object', 'category']).T
    stats_cat['freq'] = stats_cat['freq'].astype(int)
    stats_cat['top_%'] = stats_cat['freq']/len(df)*100
    stats_cat = stats_cat.rename(columns={'freq':'top_freq'})

    if round_decimals is not None:
        stats_cat = stats_cat.round(round_decimals)

    return stats_cat.T

