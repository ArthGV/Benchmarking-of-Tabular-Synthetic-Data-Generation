def generate_census_profiling_report(census, output_folder, output_file_name='census_report.html', is_export_html=True):
    """
    Generate a ydata profiling report for the census dataset.
    For more information about setting variables, 
    see https://docs.profiling.ydata.ai/latest/advanced_settings/available_settings/#correlations.

    Parameters
    ----------
    census : pd.DataFrame
        The census dataset.
    output_folder : pathlib.Path
        The folder to save the report.
    output_file_name : str, optional
        The name of the output file, by default 'census_eda_report.html'

    Returns
    -------
    pandas_profiling.ProfileReport
        The profiling report.
    """

    profiling_data = census.copy()
    ProfileReport(profiling_data)

    report = profiling_data.profile_report(
        title="Original - 2011 UK Census Microdata",
        dataset={
            "description": "This report was generated by replacing all '-9' undefined values by None. The data come from the original 2011 UK Census Microdata dataset.",
            "url": "https://www.ons.gov.uk/census/2011census/2011censusdata/censusmicrodata",
        },
        type_schema={col:"categorical" for col in census.columns},
        explorative=True,
        vars={
            "cat": {
                "length": False,
                "characters": False,
                "words": False,
                },
        },
        missing_diagrams={
            "matrix": True,
            "heatmap": True
        },
        correlations={
            "auto": {
                "calculate": False
            },
            "cramers": {
                "calculate": True
            }
        },
    )

    if is_export_html:
        with warnings.catch_warnings():
            warnings.simplefilter(action='ignore', category=FutureWarning)
            report.to_file(output_folder/output_file_name)

    return report


